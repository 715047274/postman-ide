import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const __dirname = dirname(fileURLToPath(import.meta.url))
const root = join(__dirname, '..')
const builtHtmlPath = join(root, 'dist-visualizer', 'index.html')
const outDir = join(root, 'dist')

let html
try {
  html = readFileSync(builtHtmlPath, 'utf-8')
} catch {
  console.error(
    `Could not find ${builtHtmlPath}. Run "npm run build:visualizer" (this script is the second half of that command).`
  )
  process.exit(1)
}

// Strip the dev-only CSP meta tag — Postman applies its own to the iframe
// regardless of what's in the document.
html = html.replace(/\s*<meta http-equiv="Content-Security-Policy"[^>]*>\n?/, '\n')

// Escape backslashes, backticks, and ${...} so the built HTML/JS can live
// safely inside a JS template literal.
const escaped = html.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${')

const script = `// Auto-generated by "npm run build:visualizer".
// Paste this whole file into Postman's "Tests" tab (or "Post-response" script) for the request.
let template = \`${escaped}\`;

pm.visualizer.set(template, pm.response.json());
`

mkdirSync(outDir, { recursive: true })
const outPath = join(outDir, 'postman-script.js')
writeFileSync(outPath, script)

console.log(`✔ wrote ${outPath}`)
console.log('  Paste its contents into Postman → Tests tab, then hit Send + open the Visualize tab.')
